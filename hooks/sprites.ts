// Nox's pixel sprites, „Nox fein + Knuddel“ (format nox-sprites/2), kept in
// this module, so noxdeck reads no file at run time. Each size
// (Nox 32 × 32, the mini owl 16 × 16) has its frames, a grid each: a line per
// row of pixels, a character per pixel, '.' transparent, the legend naming each
// character; and five costumes, each with the fourteen states: a state's frames
// in order, with how long each shows. A palette colors each character.
//
// The frames are kept packed, as plain grids being some 570 KB: each size names each
// distinct row once, run-length coded (a count before a character repeats it:
// `3.DMD20.DMD3.` is `...DMD....................DMD...`), one to a line, and
// each frame is a line of its rows' numbers, two characters each (DIGITS,
// base 64). Unpacked when the module loads, every frame is its grid again,
// character for character: tests/noxdeck.test.tsx compares the SHA-256 of the
// frames and times with a recorded one. hooks/fine.ts picks, times and colors them.

import type { NoxCostume, NoxState } from '../types'

/** The `noxPalette` option's names. */
export type PaletteName = 'standard' | 'nacht' | 'retro'

/** A state's frames in order, each with how long it shows in ms. */
export type Sequence = readonly (readonly [frame: number, ms: number])[]

/** One costume: each state an animation of its frames. */
export type CostumeSheet = { states: Readonly<Record<NoxState, Sequence>> }

/** One size's sprites: its frames, every costume's, and each costume's states. */
export type SpriteSheet = {
  width: number
  height: number
  frames: readonly (readonly string[])[]
  costumes: Readonly<Record<NoxCostume, CostumeSheet>>
}

export type NoxSprites = {
  format: 'nox-sprites/2'
  design: string
  name: string
  note: string
  /** What each character is; every one but transparent has a color in every palette. */
  legend: Readonly<Record<string, string>>
  /** Colors by character, as #rrggbb. */
  palettes: Readonly<Record<PaletteName, Readonly<Record<string, string>>>>
  /** Each costume's name as the sprites give it. */
  costumes: Readonly<Record<NoxCostume, string>>
  /** Nox, 32 × 32, and the mini owl, 16 × 16. */
  sizes: { big: SpriteSheet; mini: SpriteSheet }
}

/** A row's number in a frame's line: two of these characters, the first counting 64s. */
const DIGITS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ-_'

/** A row as kept: each count before a character repeats it. */
const unrun = (packed: string): string => packed.replace(/(\d+)(\D)/g, (_, count: string, pixel: string) => pixel.repeat(Number(count)))

/** The frames of a size: its rows unpacked, each frame its rows by number. */
function framesOf(rows: string, frames: string): string[][] {
  const lines = rows.trim().split('\n').map(unrun)
  return frames.trim().split('\n').map(frame => {
    const grid: string[] = []
    for (let at = 0; at < frame.length; at += 2) {
      const row = lines[DIGITS.indexOf(frame.charAt(at)) * 64 + DIGITS.indexOf(frame.charAt(at + 1))]
      if (row === undefined) throw new Error(`sprites: no row ${frame.slice(at, at + 2)}`)
      grid.push(row)
    }
    return grid
  })
}

